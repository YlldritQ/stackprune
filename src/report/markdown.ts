import type { Integration, ScanResult, Verdict } from '../types.js';
import { costOf, evidenceSummary, money, summarize, targetsOf } from './format.js';

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

const HEADINGS: Record<Verdict, string> = {
  cut: '✂️ Cut — not used, safe to remove',
  review: '🔍 Review — used, but something looks off',
  keep: '✅ Keep — in use',
};

function table(items: Integration[], currency: string): string {
  const rows = items.map(
    (i) =>
      `| **${esc(i.vendor.name)}** | ${i.vendor.category} | ${esc(targetsOf(i, 4))} | ${costOf(i, currency)} | ${esc(i.reasons.join(' · '))} | ${esc(evidenceSummary(i))} | ${esc(i.owner ?? '—')} |`,
  );
  return ['| Integration | Category | Where | Cost | Why | Evidence | Owner |', '|---|---|---|---|---|---|---|', ...rows].join('\n');
}

export function renderMarkdown(r: ScanResult): string {
  const s = summarize(r);
  const out: string[] = [];
  out.push('# stackprune report');
  out.push('');
  out.push(
    `${r.targets.length} ${r.targets.length === 1 ? 'repo' : 'repos'} · **${s.total} integrations** · ${s.byVerdict.cut} to cut · ${s.byVerdict.review} to review · ${s.byVerdict.keep} to keep` +
      (s.savingsCut ? ` · potential savings **${money(s.savingsCut, r.currency)}/mo**` : '') +
      (s.savingsReview ? ` (+${money(s.savingsReview, r.currency)}/mo under review)` : ''),
  );
  if (s.aiIntroduced) out.push('', `> ${s.aiIntroduced} integrations were added in AI-assisted commits${s.aiIntroducedUnused ? `, and ${s.aiIntroducedUnused} of those are unused` : ''}.`);
  if (r.usageWindow) out.push('', `Runtime data: ${r.usageWindow.from.slice(0, 10)} → ${r.usageWindow.to.slice(0, 10)}`);

  for (const v of ['cut', 'review', 'keep'] as Verdict[]) {
    const items = r.integrations.filter((i) => i.verdict === v);
    if (!items.length) continue;
    out.push('', `## ${HEADINGS[v]} (${items.length})`, '', table(items, r.currency));
  }

  if (r.unknownHosts.length) {
    out.push('', '## Unknown external domains', '', 'Referenced in code but not in the vendor catalog. Add the real integrations under `vendors:` in `stackprune.yml`.', '');
    out.push('| Domain | Files | Where | Hosts |', '|---|---|---|---|');
    for (const h of r.unknownHosts.slice(0, 30)) out.push(`| ${h.domain} | ${h.files}${h.calls ? ` · ${h.calls} calls` : ''} | ${esc(h.targets.join(', '))} | ${esc(h.hosts.slice(0, 5).join(', '))} |`);
  }
  out.push('', `<sub>Generated by [stackprune](https://github.com/YlldritQ/stackprune) on ${r.generatedAt.slice(0, 10)}</sub>`, '');
  return out.join('\n');
}
